"use client";

import { useEffect, useState } from "react";
import { usePathname, useRouter } from "next/navigation";
import Sidebar from "./Sidebar";
import Header from "./Header";
import { ToastProvider } from "@/components/ui/Toast";
import { useAuth } from "@/lib/auth";

const PUBLIC_ROUTES = ["/", "/login", "/register"];

export default function AppLayout({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  const router = useRouter();
  const { user, loading } = useAuth();
  const [menuOpen, setMenuOpen] = useState(false);

  const isPublicRoute = PUBLIC_ROUTES.includes(pathname);

  useEffect(() => {
    if (!loading && !user && !isPublicRoute) {
      router.replace(`/login?next=${encodeURIComponent(pathname)}`);
    }
  }, [loading, user, isPublicRoute, pathname, router]);

  if (isPublicRoute) {
    return <>{children}</>;
  }

  if (loading || !user) {
    return (
      <div className="min-h-screen flex items-center justify-center text-sm text-slate-400">
        Loading your session…
      </div>
    );
  }

  return (
    <ToastProvider>
      <a
        href="#main-content"
        className="sr-only focus:not-sr-only focus:absolute focus:z-[90] focus:top-2 focus:left-2 focus:bg-white focus:px-4 focus:py-2 focus:rounded-lg focus:text-sm focus:font-semibold focus:text-primary focus:shadow-lg"
      >
        Skip to content
      </a>
      <div className="min-h-screen flex bg-page">
        <Sidebar mobileOpen={menuOpen} onClose={() => setMenuOpen(false)} />
        <div className="flex-1 min-w-0 flex flex-col">
          <Header onMenu={() => setMenuOpen(true)} />
          <main id="main-content" className="flex-1 px-4 sm:px-8 py-8">
            <div className="max-w-[1200px] mx-auto">{children}</div>
          </main>
          <footer className="px-4 sm:px-8 pb-6">
            <p className="text-xs text-slate-400 text-center">
              LectureLoop — study material generated by the AI pipeline.
            </p>
          </footer>
        </div>
      </div>
    </ToastProvider>
  );
}
